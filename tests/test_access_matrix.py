def test_the_selection_prompt_shows_the_roster_it_is_choosing_from(run: LoopRun) -> None:
    """The roster must be in the prompt, not an argument, or no test can see who was offered."""
    for _system, prompt in run.client.prompts_for(Role.ADVISOR_SELECTION):
        offered = set(ROSTER_ENTRY.findall(prompt))
        assert offered, "no roster markers in the selection prompt"
        assert offered <= {p.persona_id for p in run.personas}


def test_the_advisor_records_why_it_chose(run: LoopRun) -> None:
    """A selection with no stated reason is not a modelled decision, just an outcome."""
    for record in run.routing:
        assert record.mode == "advisor"
        assert record.rationale.strip(), "selection carries no rationale"
        assert record.roster, "selection did not record who was on offer"


def test_a_persona_the_advisor_invents_is_never_consulted(run: LoopRun) -> None:
    """A model naming someone off-roster must be refused, or exclusion means nothing."""
    for record in run.routing:
        assert set(record.selected) <= set(record.roster)
        assert not set(record.hallucinated) & set(record.selected)


# ---------------------------------------------------------------------------
# Forced exclusion. "As though they never existed" is a claim about prompts, not
# about routing outcomes.
# ---------------------------------------------------------------------------


def test_an_excluded_theorist_reaches_no_prompt_of_any_role() -> None:
    """The intervention is that the world never had them, not that nobody picked them.

    Checked on the id and the display name, in every prompt of every role. If the name
    survived anywhere the Advisor could still be influenced by knowing they exist, and the
    exclusion contrast would be measuring something weaker than it claims.
    """
    excluded = "schelling"
    run = LoopRun(excluded=[excluded])
    persona = next(p for p in load_registry() if p.persona_id == excluded)

    assert run.opinions, "no opinions collected; the scan proves nothing"
    for text in run.all_texts():
        assert excluded not in text.lower()
        assert persona.name.lower() not in text.lower()

    for record in run.routing:
        assert excluded not in record.roster
        assert excluded not in record.selected
    assert excluded not in {o.persona_id for o in run.opinions}


def test_the_surviving_panel_is_exactly_one_smaller() -> None:
    """A silently-unchanged panel would make every exclusion arm a duplicate of baseline."""
    full = LoopRun()
    minus_one = LoopRun(excluded=["schelling"])
    assert len(minus_one.personas) == len(full.personas) - 1
    assert {p.persona_id for p in full.personas} - {p.persona_id for p in minus_one.personas} == {
        "schelling"
    }


def test_excluding_an_unknown_theorist_raises_rather_than_running() -> None:
    """An arm excluding someone who does not exist would run and duplicate baseline."""
    with pytest.raises(ValueError):
        build_panel(RunConfig(arm="typo", excluded_personas=["schelibg"]), random.Random(0))


def test_the_guard_matches_whole_words_not_substrings() -> None:
    """A guard that fires on ordinary prose gets switched off, which is worse than useless.

    The scenario contributes the token "tel" from the event label `tel_dispersal`. Under
    substring matching that fired inside "intelligence", which aborted a perfectly clean
    presidential query on the first live run. The mock never produced ordinary English, so
    only a live call could surface it.
    """
    forbidden = ["Nation A", "Nation B", "TEL", "dispersal", "garrison"]

    # Ordinary prose that merely contains the letters must pass.
    for clean in (
        "How should intelligence uncertainty shape a response?",
        "What does satellite coverage imply for warning time?",
        "Is telling an adversary your red lines stabilising?",
    ):
        assert_decontextualised(clean, forbidden, where="test")

    # The tokens themselves, as words, must still be caught.
    for leak in (
        "What should we infer from the TEL movement?",
        "How should we read a dispersal of mobile launchers?",
        "What does Nation B intend?",
    ):
        with pytest.raises(BoundaryViolation):
            assert_decontextualised(leak, forbidden, where="test")


def test_no_prompt_uses_a_real_persona_id_as_a_worked_example() -> None:
    """An example id is still that persona's name appearing in a prompt.

    A format example written as `["brodie", "schelling"]` put an excluded theorist back
    into the selection prompt, which is exactly what forced exclusion is supposed to
    prevent. Examples must use ids that belong to nobody.

    Both roles legitimately list real ids and names in their *data* section — the roster
    for selection, the collected opinions for COAs (`test_the_advisor_sees_full_opinions_
    to_write_the_coas` guards that this stays true). A blanket scan of the whole prompt
    would flag that legitimate data as if it were a leak. So this checks only the
    *instructions* tail of each prompt — the format rules and worked examples that follow
    the data — which should never reference a persona at all. The same mistake recurred
    there once already: `ADVISOR_COAS`'s citation-format example was first written as
    "q0:schelling" on the first live run of ADR 0006.
    """
    run = LoopRun()
    real_ids = {p.persona_id for p in load_registry()}
    real_names = {p.name.lower() for p in load_registry()}
    # Where each role's instructions begin, right after its data section ends.
    instructions_start = {
        Role.ADVISOR_SELECTION: "Select exactly",
        Role.ADVISOR_COAS: "AVAILABLE ACTIONS",
    }
    for role, marker in instructions_start.items():
        for _system, prompt in run.client.prompts_for(role):
            assert marker in prompt, f"{role.value} is missing its instructions marker {marker!r}"
            instructions = prompt.split(marker, 1)[1].lower()
            leaked_ids = {
                pid for pid in real_ids if re.search(rf"\b{re.escape(pid)}\b", instructions)
            }
            leaked_names = {name for name in real_names if name in instructions}
            assert not leaked_ids, (
                f"{role.value} instructions used real id(s) {leaked_ids} as an example"
            )
            assert not leaked_names, (
                f"{role.value} instructions used real name(s) {leaked_names} as an example"
            )
